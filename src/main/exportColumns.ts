/** 只保留勾选的列，按清单顺序输出；未勾选或列名未知时返回原样 */
export type Row = Record<string, string | number | null | undefined>

export function projectColumns(rows: Row[], columns?: string[]): Row[] {
  const keep = columns?.length ? COMPLAINT_COLUMNS.filter((name) => columns.includes(name)) : []
  if (!keep.length) return rows
  return rows.map((row) => {
    const out: Row = {}
    for (const name of keep) out[name] = row[name] ?? ''
    return out
  })
}

